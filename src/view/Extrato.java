    private void carregarDadosTela() {
        // Preenche Nome e CPF
        lb_nome2.setText(investidor.getNome());
        lb_cpf2.setText(investidor.getCpf());
        
        // Obtém as transações do controlador
        ControleExtrato controle = new ControleExtrato(investidor);
        ArrayList<String> transacoes = controle.obterTodasTransacoes();
        
        // Array com os 5 labels da tela
        javax.swing.JLabel[] labelsExtrato = {lb_extrato1, lb_extrato2, lb_extrato3, lb_extrato4, lb_extrato5};
        
        // Preenche até 5 linhas nas labels disponíveis
        for (int i = 0; i < labelsExtrato.length; i++) {
            if (i < transacoes.size()) {
                labelsExtrato[i].setText(transacoes.get(i));
            } else {
                labelsExtrato[i].setText(""); // Deixa vazio se não houver transação
            }
        }
    }
    

